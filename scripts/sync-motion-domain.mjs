import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const output = new URL("services/video-worker/src/motion/generated/", root);
await mkdir(output, { recursive: true });
for (const name of ["types", "contract", "lint", "prompt-builder", "reference-brief"]) {
  const source = await readFile(new URL(`src/domain/motion/${name}.ts`, root), "utf8");
  const rewritten = source.replace(/from (["'])\.\/([a-z-]+)\1/g, 'from "./$2.js"');
  await writeFile(
    new URL(`${name}.ts`, output),
    `// Generated by scripts/sync-motion-domain.mjs from src/domain/motion/${name}.ts.\n// Do not edit this worker copy.\n${rewritten}`,
  );
}
console.log(`Synchronized Motion Studio domain to ${fileURLToPath(output)}`);
